package org.saidone.config;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.stereotype.Component;
import org.springframework.validation.annotation.Validated;

/** Controls new binary writes only; stored encoding always controls reads. */
@Component
@ConfigurationProperties(prefix = "application.service.vault.compression")
@Validated
@Data
public class ContentCompressionConfig {
    private boolean enabled;

    @Min(1)
    @Max(9)
    private int level = 3;
}
